// Regenerates assets/js/icons.js: the Lucide icons this app uses, as inline SVG markup (no Lucide runtime, no CDN).
//   node scripts/build-icons.mjs [path/to/lucide.js]      (default: downloads lucide@0.468.0 UMD from unpkg)
// Icon names are collected from the source: data-lucide="x", icon('x'), icon: 'x', registry entries, and every quoted
// name on a line that mentions icon/lucide. Run it again after using a new icon (tests/unit/icons.test.mjs tells you).
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { TOOLS, CATEGORIES } from '../assets/js/registry.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SKIP = new Set(['node_modules', '.git', 'vendor', 'excel-editor', 'word-editor', 'tests', 'docs', 'scripts']);
const files = [];
(function walk(d) {
  for (const f of readdirSync(d)) {
    if (SKIP.has(f)) continue;
    const p = join(d, f), s = statSync(p);
    if (s.isDirectory()) walk(p); else if (/\.(js|html)$/.test(f) && f !== 'icons.js') files.push(p);
  }
})(root);

const pascal = n => n.replace(/(\w)(\w*)(_|-|\s*)/g, (g0, g1, g2) => g1.toUpperCase() + g2.toLowerCase());
const src = process.argv[2] ? readFileSync(process.argv[2], 'utf8') : await (await fetch('https://unpkg.com/lucide@0.468.0/dist/umd/lucide.js')).text();
const m = { exports: {} }; globalThis.window = globalThis; globalThis.self = globalThis; globalThis.document = {};
new Function('module', 'exports', src)(m, m.exports);
const lucide = m.exports.icons ? m.exports : globalThis.lucide, icons = lucide.icons;

const names = new Set([...TOOLS.map(t => t.icon), ...CATEGORIES.map(c => c.icon)]);
for (const f of files) {
  for (const line of readFileSync(f, 'utf8').split('\n')) {
    if (!/icon|lucide/i.test(line)) continue;
    for (const x of line.matchAll(/['"`]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)['"`]/g)) if (icons[pascal(x[1])]) names.add(x[1]);
    for (const x of line.matchAll(/data-lucide="([a-z0-9-]+)"/g)) names.add(x[1]);
  }
}
const esc = s => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
const body = [...names].sort().filter(n => icons[pascal(n)]).map(n => {
  const inner = icons[pascal(n)][2].map(([tag, a]) => `<${tag} ${Object.entries(a).map(([k, v]) => `${k}="${v}"`).join(' ')}/>`).join('');
  return `  '${n}': '${esc(inner)}',`;
}).join('\n');
writeFileSync(join(root, 'assets/js/icons.js'), `// GENERATED by scripts/build-icons.mjs from Lucide 0.468.0 (ISC licence, see assets/js/vendor/LICENSE-lucide.txt). Do not edit by hand.
// Inner SVG markup (24x24 viewBox, stroke icons) for every icon the app uses.
export const ICONS = {
${body}
};
`);
console.log(`wrote ${[...names].filter(n => icons[pascal(n)]).length} icons; unknown names skipped:`, [...names].filter(n => !icons[pascal(n)]));
